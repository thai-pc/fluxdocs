// symbolAlt maps Symbol glyph names whose AGL value is a private-use
// character (U+F6D9–F6DB, U+F8E5–F8FE), or a character DejaVu Sans lacks
// (U+2329, U+232A, U+23AF, U+23D0), to a standard character of the same
// appearance, chosen from the Unicode code charts (Latin-1 Supplement,
// Letterlike Symbols, Miscellaneous Technical, Box Drawing, Miscellaneous
// Mathematical Symbols-A). It must equal std14's symbolAlt
// (core/internal/std14/symbol.go); a std14 test checks the two agree with
// the face.
var symbolAlt = map[string]rune{
	"copyrightsans": 0x00A9, "copyrightserif": 0x00A9,
	"registersans": 0x00AE, "registerserif": 0x00AE,
	"trademarksans": 0x2122, "trademarkserif": 0x2122,
	"arrowvertex": 0x2502, "arrowhorizex": 0x2500,
	"angleleft": 0x27E8, "angleright": 0x27E9,
	"parenlefttp": 0x239B, "parenleftex": 0x239C, "parenleftbt": 0x239D,
	"parenrighttp": 0x239E, "parenrightex": 0x239F, "parenrightbt": 0x23A0,
	"bracketlefttp": 0x23A1, "bracketleftex": 0x23A2, "bracketleftbt": 0x23A3,
	"bracketrighttp": 0x23A4, "bracketrightex": 0x23A5, "bracketrightbt": 0x23A6,
	"bracelefttp": 0x23A7, "braceleftmid": 0x23A8, "braceleftbt": 0x23A9,
	"bracerighttp": 0x23AB, "bracerightmid": 0x23AC, "bracerightbt": 0x23AD,
	"braceex": 0x23AA, "integralex": 0x23AE,
}

// genAFM writes core/internal/std14/afm_gen.go.
func genAFM(afms map[string]*afm) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by testing/tools/std14fonts; DO NOT EDIT.\n\n")
	b.WriteString("// Derived from the Adobe Core 14 AFM files (Core14_AFMs.zip). Modified:\n")
	b.WriteString("// the character widths, FontBBox values and built-in encodings were\n")
	b.WriteString("// extracted to Go tables; nothing else of the files is included. License:\n")
	b.WriteString("// LICENSES/APAFML.txt. Copyright notices of the AFM files:\n//\n")
	seen := map[string]bool{}
	for _, af := range afmFaces {
		for _, line := range strings.Split(string(afmSource[af.file]), "\n") {
			line = strings.TrimRight(line, "\r")
			if strings.HasPrefix(line, "Notice ") && !seen[line] {
				seen[line] = true
				b.WriteString("//   " + strings.TrimPrefix(line, "Notice ") + "\n")
			}
		}
	}
	b.WriteString("\npackage std14\n\n")

	// Latin: one sorted name list shared by the 12 faces.
	nameSet := map[string]bool{}
	for _, af := range afmFaces[:12] {
		for _, g := range afms[af.file].glyphs {
			nameSet[g.name] = true
		}
	}
	latin := sortedKeys(nameSet)
	b.WriteString("// afmLatinNames is the sorted union of the glyph names of the 12 Latin\n// faces' AFM files.\n")
	writeStrings(&b, "afmLatinNames", latin)
	fmt.Fprintf(&b, "// afmLatinWidths[face][i] is the width (WX) of afmLatinNames[i] in the\n// face, or noWidth when its AFM lacks the glyph.\nvar afmLatinWidths = [12][%d]uint16{\n", len(latin))
	for _, af := range afmFaces[:12] {
		w := map[string]int{}
		for _, g := range afms[af.file].glyphs {
			w[g.name] = g.width
		}
		fmt.Fprintf(&b, "%s: {", af.face)
		for i, n := range latin {
			if i%16 == 0 {
				b.WriteString("\n")
			}
			if v, ok := w[n]; ok {
				fmt.Fprintf(&b, "%d, ", v)
			} else {
				b.WriteString("noWidth, ")
			}
		}
		b.WriteString("\n},\n")
	}
	b.WriteString("}\n\n")

	for _, sf := range []struct{ file, id string }{{"Symbol.afm", "Symbol"}, {"ZapfDingbats.afm", "Dingbats"}} {
		a := afms[sf.file]
		gs := append([]afmGlyph(nil), a.glyphs...)
		sort.Slice(gs, func(i, j int) bool { return gs[i].name < gs[j].name })
		var names []string
		for i, g := range gs {
			if i > 0 && g.name == gs[i-1].name {
				log.Fatalf("%s: duplicate %s", sf.file, g.name)
			}
			names = append(names, g.name)
		}
		fmt.Fprintf(&b, "// afm%sNames is the sorted glyph names of %s.\n", sf.id, sf.file)
		writeStrings(&b, "afm"+sf.id+"Names", names)
		fmt.Fprintf(&b, "// afm%sWidths[i] is the width (WX) of afm%sNames[i].\nvar afm%sWidths = [...]uint16{", sf.id, sf.id, sf.id)
		for i, g := range gs {
			if i%16 == 0 {
				b.WriteString("\n")
			}
			fmt.Fprintf(&b, "%d, ", g.width)
		}
		b.WriteString("\n}\n\n")
		fmt.Fprintf(&b, "// %sBuiltin is the built-in encoding of %s (its C values).\nvar %sBuiltin = Encoding{", strings.ToLower(sf.id[:1])+sf.id[1:], sf.file, strings.ToLower(sf.id[:1])+sf.id[1:])
		byCode := append([]afmGlyph(nil), a.glyphs...)
		sort.Slice(byCode, func(i, j int) bool { return byCode[i].code < byCode[j].code })
		n := 0
		for _, g := range byCode {
			if g.code < 0 {
				continue
			}
			if n%6 == 0 {
				b.WriteString("\n")
			}
			n++
			fmt.Fprintf(&b, "%d: %q, ", g.code, g.name)
		}
		b.WriteString("\n}\n\n")
	}

	b.WriteString("// afmBBox is each face's FontBBox (llx lly urx ury), in glyph units.\nvar afmBBox = [NumFaces][4]int16{\n")
	for _, af := range afmFaces {
		bb := afms[af.file].bbox
		fmt.Fprintf(&b, "%s: {%d, %d, %d, %d},\n", af.face, bb[0], bb[1], bb[2], bb[3])
	}
	b.WriteString("}\n")
	return gofmt(b.Bytes())
}

// genAGL writes core/internal/std14/agl_gen.go: the AGL and zapfdingbats
// entries for every glyph name the AFM files use, and every other AGL name
// whose (single) value some substitute face maps (kept).
func genAGL(agl, zapf map[string][]rune, afms map[string]*afm, kept map[rune]bool) []byte {
	want := map[string]rune{}
	add := func(name string, r rune) {
		if old, ok := want[name]; ok && old != r {
			log.Fatalf("glyph name %s: %04X and %04X", name, old, r)
		}
		if r > 0xFFFF {
			log.Fatalf("glyph name %s: %04X is outside the BMP", name, r)
		}
		want[name] = r
	}
	for name, rs := range agl {
		if kept[rs[0]] {
			add(name, rs[0])
		}
	}
	for _, af := range afmFaces {
		for _, g := range afms[af.file].glyphs {
			switch {
			case af.face == "ZapfDingbats" && len(zapf[g.name]) > 0:
				add(g.name, zapf[g.name][0])
			case len(agl[g.name]) > 0:
				add(g.name, agl[g.name][0])
			default:
				log.Fatalf("%s: %s has no AGL value", af.file, g.name)
			}
		}
	}
	names := make([]string, 0, len(want))
	for n := range want {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by testing/tools/std14fonts; DO NOT EDIT.\n\n")
	b.WriteString("// Selected entries of the Adobe Glyph List (glyphlist.txt) and the ITC\n")
	b.WriteString("// Zapf Dingbats glyph list (zapfdingbats.txt), github.com/adobe-type-tools/\n")
	b.WriteString("// agl-aglfn. Copyright 2002-2019 Adobe (http://www.adobe.com/).\n")
	b.WriteString("// BSD 3-Clause License: LICENSES/BSD-3-Clause-AGL.txt.\n\npackage std14\n\n")
	b.WriteString("// aglNames is the sorted glyph names; aglRunes[i] is aglNames[i]'s Unicode\n// value.\n")
	writeStrings(&b, "aglNames", names)
	b.WriteString("var aglRunes = [...]uint16{")
	for i, n := range names {
		if i%12 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%04X, ", want[n])
	}
	b.WriteString("\n}\n")
	return gofmt(b.Bytes())
}

func writeStrings(b *bytes.Buffer, name string, ss []string) {
	fmt.Fprintf(b, "var %s = [...]string{", name)
	line := -1
	for _, s := range ss {
		q := fmt.Sprintf("%q, ", s)
		if line < 0 || line+len(q) > 72 {
			b.WriteString("\n")
			line = 0
		}
		b.WriteString(q)
		line += len(q)
	}
	b.WriteString("\n}\n\n")
}

func sortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func gofmt(src []byte) []byte {
	out, err := format.Source(src)
	if err != nil {
		log.Fatalf("generated code: %v", err)
	}
	return out
}
