#!/usr/bin/env bash
# generate.sh writes the AES-256 fixtures of testing/corpus/encrypted and their
# MANIFEST.tsv (docs/design/aes256-decryption.md §11.1). Maintainer-run, never
# in CI; its output is committed.
#
#   Option 1: synthetic one-page PDFs (main.go) encrypted by the qpdf command
#             line, with documented options only (`--encrypt`, `--bits=256`,
#             `--force-R5`, `--cleartext-metadata`, `--object-streams=generate`).
#             Skipped, with a note, when qpdf is not installed.
#   Option 3: documents the FluxDocs test-only encryptor writes
#             (core/parse/crypt_v5_fixtures_test.go) for what the qpdf command
#             line cannot produce.
#   Option 2: Ghostscript, a second independent program, reads every fixture
#             with its passwords and must find the marker; qpdf, when installed,
#             runs `--check` and decrypts every fixture too. A fixture that
#             fails a required check stops the script, so it is never recorded.
#
# qpdf (Apache-2.0) and Ghostscript (AGPL) run only as separate processes on
# synthetic inputs: nothing links them, and their source is never read.
#
# Usage, from the repository root:
#   testing/tools/aes256vectors/generate.sh [output-dir]   # default testing/corpus/encrypted
set -euo pipefail

out="${1:-testing/corpus/encrypted}"
work="$(mktemp -d)"
trap 'rm -rf -- "${work:?}"' EXIT

command -v gs >/dev/null || { echo "generate.sh: Ghostscript (gs) is required" >&2; exit 1; }
gsver="$(gs --version)"
qpdfver=""
if command -v qpdf >/dev/null; then
  qpdfver="$(qpdf --version | head -n1 | sed 's/^qpdf version //')"
else
  echo "generate.sh: qpdf not installed: the qpdf-encrypted cases are skipped" >&2
fi

hex() { printf '%s' "$1" | od -An -tx1 | tr -d ' \n'; }

# gs_reads FILE PASSWORD MARKER: Ghostscript's text output holds the marker.
gs_reads() {
  gs -q -dNOPAUSE -dBATCH -dSAFER -sDEVICE=txtwrite -sOutputFile=- \
    -sPDFPassword="$2" "$1" 2>/dev/null | tr -d '\000' | grep -q -- "$3"
}

# qpdf_reads FILE PASSWORD MARKER: qpdf --check passes and the decrypted,
# uncompressed (QDF) output holds the marker.
qpdf_reads() {
  qpdf --check --password="$2" "$1" >/dev/null 2>&1 || return 1
  qpdf --qdf --object-streams=disable --password="$2" --decrypt "$1" "$work/dec.pdf" >/dev/null 2>&1 || return 1
  grep -aq -- "$3" "$work/dec.pdf"
}

manifest="$work/MANIFEST.tsv"
printf '# file\tproducer\tR\tuser_password_utf8_hex\towner_password_utf8_hex\tmarker\tgs_user\tgs_owner\tqpdf_user\tqpdf_owner\tsha256\n' >"$manifest"
printf '# Ghostscript %s; qpdf %s; generated by testing/tools/aes256vectors/generate.sh\n' "$gsver" "${qpdfver:-not installed}" >>"$manifest"

# record FILE PRODUCER R USER OWNER MARKER [gs-user-optional]
record() {
  local f="$1" producer="$2" r="$3" user="$4" owner="$5" marker="$6" optional="${7:-}"
  # The only tolerated failure: Ghostscript and R5 with an empty user password.
  if [ -n "$optional" ] && { [ "$optional" != gs-r5-empty ] || [ "$r" != 5 ] || [ -n "$user" ]; }; then
    echo "generate.sh: $(basename "$f"): no skip allowed here" >&2
    exit 1
  fi
  local gsu=fail gso=fail qu=- qo=-
  gs_reads "$f" "$user" "$marker" && gsu=ok
  gs_reads "$f" "$owner" "$marker" && gso=ok
  if [ "$gso" != ok ] || { [ "$gsu" != ok ] && [ -z "$optional" ]; }; then
    echo "generate.sh: Ghostscript does not read $(basename "$f") (user $gsu, owner $gso)" >&2
    exit 1
  fi
  if [ -n "$qpdfver" ]; then
    qu=fail qo=fail
    qpdf_reads "$f" "$user" "$marker" && qu=ok
    qpdf_reads "$f" "$owner" "$marker" && qo=ok
    if [ "$qu" != ok ] || [ "$qo" != ok ]; then
      echo "generate.sh: qpdf does not read $(basename "$f") (user $qu, owner $qo)" >&2
      exit 1
    fi
  fi
  local sum
  sum="$(shasum -a 256 "$f" | cut -d' ' -f1)"
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$(basename "$f")" "$producer" "$r" \
    "$(hex "$user")" "$(hex "$owner")" "$marker" "$gsu" "$gso" "$qu" "$qo" "$sum" >>"$manifest"
  cp "$f" "$out/"
}

# Option 1: qpdf. Each case: name, R, user password, owner password, qpdf
# options inside --encrypt … --, source flags. Non-ASCII passwords are UTF-8
# bytes written as \x escapes (bash 3.2 has no \u): ä c3a4, ö c3b6,
# U+00AD c2ad, U+3000 e38080, fullwidth P A S efbcb0 efbca1 efbcb3.
cases=(
  "r6_owner_only|6||owner||"
  "r6_user|6|user|owner||"
  "r6_same|6|same|same||"
  "r6_umlaut|6|p"$'\xc3\xa4'"ssw"$'\xc3\xb6'"rd|owner||"
  "r6_soft_hyphen|6|pass"$'\xc2\xad'"word|owner||"
  "r6_ideographic_space|6|pass"$'\xe3\x80\x80'"word|owner||"
  "r6_fullwidth|6|"$'\xef\xbc\xb0\xef\xbc\xa1\xef\xbc\xb3\xef\xbc\xb3'"|owner||"
  "r6_cleartext_metadata|6|user|owner|--cleartext-metadata|-meta"
  "r6_objstm|6|user|owner||"
  "r5_user|5|user|owner|--force-R5|"
  "r5_owner_only|5||owner|--force-R5||gs-r5-empty"
)
if [ -n "$qpdfver" ]; then
  for c in "${cases[@]}"; do
    IFS='|' read -r name r user owner encopts srcopts gsopt <<<"$c"
    marker="AES256-OK-${name//_/-}"
    go run ./testing/tools/aes256vectors -marker "$marker" $srcopts -o "$work/src.pdf"
    args=(--encrypt "--user-password=$user" "--owner-password=$owner" --bits=256)
    [ -n "$encopts" ] && args+=($encopts)
    args+=(--)
    post=()
    [ "$r" = 5 ] && post+=(--allow-weak-crypto)
    case "$name" in *objstm*) post+=(--object-streams=generate) ;; esac
    qpdf ${post[@]+"${post[@]}"} "$work/src.pdf" "${args[@]}" "$work/qpdf_$name.pdf"
    record "$work/qpdf_$name.pdf" "qpdf $qpdfver" "$r" "$user" "$owner" "$marker" "$gsopt"
  done
  # The evidence for the one tolerated Ghostscript failure (gs_user=fail).
  printf '# gs_user=fail: Ghostscript %s does not open an R5 file with the empty user password (it does with the owner password). Reproduced on qpdf_r5_owner_only.pdf, written by qpdf, whose --show-encryption reports an empty user password and which qpdf opens with it; so the R5 handling of the reader, not of the file, is at fault.\n' "$gsver" >>"$manifest"
fi

# Stop-test regression cases: qpdf picks random salts, and about 5% of its R6
# files take a 2.B chain on which the off-by-one reading of the stop test
# (the 0-based round index instead of the round count) derives a different
# hash. Encrypt again until the file is one of them
# (core/parse TestSeparatesCheck decides), then check it like the others.
if [ -n "$qpdfver" ]; then
  go test -c -o "$work/parse.test" ./core/parse
  for c in "r6_chain_user|user|owner" "r6_chain_owner_only||owner"; do
    IFS='|' read -r name user owner <<<"$c"
    marker="AES256-OK-${name//_/-}"
    go run ./testing/tools/aes256vectors -marker "$marker" -o "$work/src.pdf"
    found=""
    for i in $(seq 1 400); do
      qpdf "$work/src.pdf" --encrypt "--user-password=$user" "--owner-password=$owner" --bits=256 -- "$work/qpdf_$name.pdf"
      if FLUXDOCS_SEPARATES="$work/qpdf_$name.pdf:$user" "$work/parse.test" -test.run '^TestSeparatesCheck$' >/dev/null 2>&1; then
        found="$i"
        break
      fi
    done
    [ -n "$found" ] || { echo "generate.sh: no separating chain for $name in 400 tries" >&2; exit 1; }
    echo "generate.sh: $name separates the stop-test readings (attempt $found)" >&2
    record "$work/qpdf_$name.pdf" "qpdf $qpdfver" 6 "$user" "$owner" "$marker"
  done
fi

# Option 3: the test-only encryptor. Ghostscript does not open an R5 file
# with the empty password (observed with 10.07.1; it does with the owner
# password; reproduced on qpdf's own R5 output, qpdf_r5_owner_only.pdf, which
# qpdf opens with the empty password), so that user check is tolerated, for
# R5 with an empty user password only (gs-r5-empty).
FLUXDOCS_AES256_FIXTURES="$work" go test -count=1 -run '^TestWriteAES256Fixtures$' ./core/parse >/dev/null
record "$work/enc_r5_empty_user.pdf" "fluxdocs test encryptor" 5 "" owner AES256-OK-enc-r5-empty-user gs-r5-empty
record "$work/enc_r6_objstm_meta.pdf" "fluxdocs test encryptor" 6 user owner AES256-OK-enc-r6-objstm-meta

cp "$manifest" "$out/MANIFEST.tsv"
cat "$out/MANIFEST.tsv"
