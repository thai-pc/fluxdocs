// Command saslprep generates core/parse/saslprep_tables.go, the stringprep
// tables SASLprep needs (RFC 4013 §2, which names tables of RFC 3454), from
// the text of RFC 3454 itself: B.1 (mapped to nothing), C.1.2 (non-ASCII
// space characters), the prohibited tables C.1.2, C.2.1, C.2.2, C.3, C.4,
// C.5, C.6, C.7, C.8 and C.9, and the bidirectional tables D.1 (RandALCat)
// and D.2 (LCat). Table A.1 (unassigned code points) is not generated: a
// password typed at open is a "query" in RFC 3454 terms (§7), so unassigned
// code points are allowed (docs/design/aes256-decryption.md §4).
//
// It is an offline, maintainer-run step, not a build dependency: its output
// is committed. The input is the plain-text RFC as published by the RFC
// Editor (https://www.rfc-editor.org/rfc/rfc3454.txt); its SHA-256 is checked
// before anything is read, and the output is deterministic, so running it
// again reproduces the committed file byte for byte. The tables are data
// transcribed from a public standard, not code from any library.
//
// Usage (from the repository root):
//
//	go run ./testing/tools/saslprep -rfc3454 rfc3454.txt [-out core/parse/saslprep_tables.go]
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strconv"
	"strings"
)

// rfc3454SHA256 pins the input: the RFC Editor's plain-text RFC 3454.
const rfc3454SHA256 = "eb722fa698fb7e8823b835d9fd263e4cdb8f1c7b0d234edf7f0e3bd2ccbb2c79"

// prohibited are the tables RFC 4013 §2.3 prohibits in SASLprep output.
var prohibited = []string{"C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9"}

type runeRange struct{ lo, hi rune }

func main() {
	in := flag.String("rfc3454", "", "path to the plain-text RFC 3454")
	out := flag.String("out", "core/parse/saslprep_tables.go", "output Go file")
	flag.Parse()
	if *in == "" {
		log.Fatal("-rfc3454 is required")
	}
	data, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != rfc3454SHA256 {
		log.Fatalf("%s: SHA-256 %s, want %s (the RFC Editor's rfc3454.txt)", *in, got, rfc3454SHA256)
	}
	tables, err := parseTables(data)
	if err != nil {
		log.Fatal(err)
	}
	need := append([]string{"B.1", "D.1", "D.2"}, prohibited...)
	for _, name := range need {
		if len(tables[name]) == 0 {
			log.Fatalf("table %s not found or empty", name)
		}
	}
	var union []runeRange
	for _, name := range prohibited {
		union = append(union, tables[name]...)
	}

	var b bytes.Buffer
	b.WriteString(`// Code generated by testing/tools/saslprep from RFC 3454; DO NOT EDIT.

// The tables below are transcribed from RFC 3454, "Preparation of
// Internationalized Strings ("stringprep")", P. Hoffman and M. Blanchet,
// December 2002, Appendix B (B.1), Appendix C (C.1.2 to C.9) and Appendix D
// (D.1, D.2), as SASLprep (RFC 4013, K. Zeilenga, February 2005, §2) uses
// them. They are code point ranges transcribed by a program that reads the
// RFC text (testing/tools/saslprep), not code from any implementation. The
// RFC's copyright notice and permission paragraph, as it requires:
//
//	Copyright (C) The Internet Society (2002).  All Rights Reserved.
//
//	This document and translations of it may be copied and furnished to
//	others, and derivative works that comment on or otherwise explain it
//	or assist in its implementation may be prepared, copied, published
//	and distributed, in whole or in part, without restriction of any
//	kind, provided that the above copyright notice and this paragraph are
//	included on all such copies and derivative works.  However, this
//	document itself may not be modified in any way, such as by removing
//	the copyright notice or references to the Internet Society or other
//	Internet organizations, except as needed for the purpose of
//	developing Internet standards in which case the procedures for
//	copyrights defined in the Internet Standards process must be
//	followed, or as required to translate it into languages other than
//	English.

package parse

`)
	emit := func(name, doc string, rs []runeRange) {
		rs = merge(rs)
		fmt.Fprintf(&b, "// %s\nvar %s = []runeRange{\n", doc, name)
		for _, r := range rs {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r.lo, r.hi)
		}
		b.WriteString("}\n\n")
	}
	emit("saslMapToNothing", "saslMapToNothing is RFC 3454 table B.1: characters commonly mapped to nothing.", tables["B.1"])
	emit("saslNonASCIISpace", "saslNonASCIISpace is RFC 3454 table C.1.2: non-ASCII space characters, mapped to U+0020 (RFC 4013 §2.1).", tables["C.1.2"])
	emit("saslProhibited", "saslProhibited is the union of RFC 3454 tables "+strings.Join(prohibited, ", ")+" (RFC 4013 §2.3).", union)
	emit("saslRandALCat", "saslRandALCat is RFC 3454 table D.1: characters with bidirectional property R or AL.", tables["D.1"])
	emit("saslLCat", "saslLCat is RFC 3454 table D.2: characters with bidirectional property L.", tables["D.2"])

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("gofmt: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	osum := sha256.Sum256(src)
	fmt.Printf("%s  %s\n", hex.EncodeToString(osum[:]), *out)
}

// parseTables reads every "----- Start Table X -----" … "----- End Table X
// -----" block of the RFC: one code point or range ("XXXX" or "XXXX-YYYY")
// per line before the first ';', skipping the page footers and headers the
// RFC's pagination puts inside a table.
func parseTables(data []byte) (map[string][]runeRange, error) {
	tables := map[string][]runeRange{}
	cur := ""
	sc := bufio.NewScanner(bytes.NewReader(data))
	line := 0
	for sc.Scan() {
		line++
		s := strings.TrimSpace(sc.Text())
		switch {
		case strings.HasPrefix(s, "----- Start Table ") && strings.HasSuffix(s, " -----"):
			if cur != "" {
				return nil, fmt.Errorf("line %d: table %s not closed", line, cur)
			}
			cur = strings.TrimSuffix(strings.TrimPrefix(s, "----- Start Table "), " -----")
			continue
		case strings.HasPrefix(s, "----- End Table "):
			name := strings.TrimSuffix(strings.TrimPrefix(s, "----- End Table "), " -----")
			if name != cur {
				return nil, fmt.Errorf("line %d: end of table %s inside %s", line, name, cur)
			}
			cur = ""
			continue
		}
		if cur == "" || s == "" || strings.HasPrefix(s, "Hoffman & Blanchet") || strings.HasPrefix(s, "RFC 3454") {
			continue
		}
		field := s
		if i := strings.IndexByte(field, ';'); i >= 0 {
			field = field[:i]
		}
		field = strings.TrimSpace(field)
		lo, hi, ok := strings.Cut(field, "-")
		if !ok {
			hi = lo
		}
		l, err1 := strconv.ParseUint(lo, 16, 32)
		h, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil || l > h || h > 0x10FFFF {
			return nil, fmt.Errorf("line %d: table %s: bad entry %q", line, cur, s)
		}
		tables[cur] = append(tables[cur], runeRange{rune(l), rune(h)})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if cur != "" {
		return nil, fmt.Errorf("table %s not closed", cur)
	}
	return tables, nil
}

// merge sorts rs and joins overlapping and adjacent ranges.
func merge(rs []runeRange) []runeRange {
	rs = append([]runeRange(nil), rs...)
	sort.Slice(rs, func(i, j int) bool { return rs[i].lo < rs[j].lo })
	var out []runeRange
	for _, r := range rs {
		if n := len(out); n > 0 && r.lo <= out[n-1].hi+1 {
			out[n-1].hi = max(out[n-1].hi, r.hi)
			continue
		}
		out = append(out, r)
	}
	return out
}
